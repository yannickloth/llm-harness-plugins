export const STE100_MARKER = "[STE-100 Simplified Technical English]"

export const STE100_RULE = `${STE100_MARKER}
Rule: When producing technical or scientific documents, reports, documentation,
or any written content in a technical/scientific context, comply with
ASD-STE100 Simplified Technical English.

Requirements:
- Approved vocabulary: use only approved STE words from the ASD-STE100 dictionary; prefer them over synonyms
- One meaning per word: use each approved word with its prescribed meaning only; never a colloquial or secondary sense
- Short sentences: keep sentences short; one idea per sentence; split long or compound sentences
- Active voice: use active voice; name the actor/agent explicitly
- Simple grammar: use present tense for general statements; avoid conditional and future where plain tense suffices
- Avoid abbreviations: use the full approved term unless the abbreviation itself is the approved STE word
- Clarity over style: prioritize unambiguous meaning over elegance; no metaphor, idiom, or literary flourish
- Structured writing: use consistent terminology throughout; define any unavoidable technical term at first use
- Sequencing: number steps in procedures; describe actions in the order they must be performed
- Negative commands: state a warning/instruction as "Do not X" rather than "X must not be done" when instructing action

Scope: applies to any deliverable that is technical or scientific in nature,
including prose, explanations, API/docs text, user guides, and inline
documentation. Not required for conversational chat, casual responses, or
non-technical prose unless the user requests it.`
